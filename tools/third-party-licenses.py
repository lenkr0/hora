"""Lizenztexte aller Rust-Crates, die in hora.exe und im Installer
(Hora-Setup, auch als uninstall.exe) eingehen – normale Abhängigkeiten von
hora-app und hora-setup für Windows, ohne Build- und Test-Abhängigkeiten –
nach THIRD_PARTY_LICENSES/Rust-Crates.txt schreiben.

    python tools/third-party-licenses.py

Braucht nur `cargo metadata` (offline, die Quellen liegen nach einem Build im
Cargo-Register). Mit --check bricht es ab, wenn die Datei veraltet ist (CI).
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES", "Rust-Crates.txt")
TARGET = "x86_64-pc-windows-msvc"
FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout
    return json.loads(out)


def shipped(meta):
    """IDs der Pakete, die mit den Standard-Features in hora-app und
    hora-setup landen.

    `cargo metadata` nimmt auch optionale Abhängigkeiten nicht gewählter
    Features mit (z. B. Skia); `cargo tree` zeigt genau den Build. Jedes
    Programm einzeln, weil Cargo Features sonst über beide vereinigt."""
    wanted = set()
    for package in ("hora-app", "hora-setup"):
        out = subprocess.run(
            ["cargo", "tree", "-p", package, "-e", "normal", "--target", TARGET,
             "--prefix", "none", "--locked", "-f", "{p}"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[1].startswith("v"):
                wanted.add((parts[0], parts[1][1:]))
    return {p["id"] for p in meta["packages"] if (p["name"], p["version"]) in wanted}


def license_files(package):
    folder = os.path.dirname(package["manifest_path"])
    found = []
    for name in sorted(os.listdir(folder)):
        upper = name.upper()
        if upper.startswith(FILES) and os.path.isfile(os.path.join(folder, name)):
            found.append(os.path.join(folder, name))
    if package.get("license_file"):
        extra = os.path.join(folder, package["license_file"])
        if os.path.isfile(extra) and extra not in found:
            found.append(extra)
    return found


def main():
    meta = metadata()
    ids = shipped(meta)
    packages = sorted(
        (p for p in meta["packages"] if p["id"] in ids and p["source"] is not None),
        key=lambda p: (p["name"].lower(), p["version"]),
    )
    lines = [
        "Licenses of the Rust libraries in hora.exe and the installer",
        "============================================================",
        "",
        "Generated by tools/third-party-licenses.py from Cargo.lock. For each crate:",
        "name, version, license and the license files of the package. Packages",
        "without their own file are listed at the end; the standard text of the",
        "named license applies to them (MIT, Apache-2.0 etc., see the texts above).",
        "",
    ]
    without = []
    texts = {}
    for p in packages:
        files = license_files(p)
        if not files:
            without.append(p)
            continue
        lines.append("-" * 78)
        lines.append(f"{p['name']} {p['version']} ({p.get('license') or 'not specified'})")
        if p.get("repository"):
            lines.append(p["repository"])
        lines.append("")
        for f in files:
            with open(f, encoding="utf-8", errors="replace") as fh:
                text = fh.read().strip()
            # Gleiche Texte (z. B. identische Apache-2.0) nur einmal ausschreiben
            key = text
            if key in texts:
                lines.append(f"[{os.path.basename(f)}: same text as {texts[key]}]")
            else:
                texts[key] = f"{p['name']} {p['version']}"
                lines.append(f"[{os.path.basename(f)}]")
                lines.append(text)
            lines.append("")
    if without:
        lines.append("-" * 78)
        lines.append("Packages without their own license file:")
        lines.append("")
        for p in without:
            lines.append(f"  {p['name']} {p['version']} ({p.get('license') or 'not specified'})")
        lines.append("")
    content = "\n".join(lines).replace("\r\n", "\n")
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != content:
            sys.exit("THIRD_PARTY_LICENSES/Rust-Crates.txt ist veraltet: python tools/third-party-licenses.py")
        print(f"{len(packages)} Crates, Datei aktuell")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    print(f"{len(packages)} Crates ({len(without)} ohne eigene Datei) -> {OUT}")


if __name__ == "__main__":
    main()
